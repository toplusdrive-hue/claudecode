#!/usr/bin/env node
// Bundles a folder of .srt files into episodes.js so the studio can open
// without a file picker (and so it works as a published, offline page).
//
//   node build-episodes.mjs [srtDir] [outFile]
//
// Default: ./srt -> ./episodes.js
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename, extname } from 'node:path';

const srtDir = process.argv[2] || new URL('./srt', import.meta.url).pathname;
const outFile = process.argv[3] || new URL('./episodes.js', import.meta.url).pathname;

const files = readdirSync(srtDir)
  .filter((f) => extname(f).toLowerCase() === '.srt')
  .sort();

const episodes = files.map((f) => {
  const raw = readFileSync(join(srtDir, f), 'utf8').replace(/^﻿/, '');
  return { code: basename(f, extname(f)), file: f, srt: raw.replace(/\r\n/g, '\n').trim() };
});

const body =
  '/* Generated by build-episodes.mjs - do not edit by hand. */\n' +
  'window.WORKBOOK_EPISODES = ' + JSON.stringify(episodes) + ';\n';

writeFileSync(outFile, body);
const kb = (Buffer.byteLength(body) / 1024).toFixed(0);
console.log(`wrote ${outFile} (${episodes.length} episodes, ${kb} KB)`);
